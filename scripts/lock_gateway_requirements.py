"""Regenerate docker/gateway/requirements.txt with hashes for every platform the gateway image supports.

Usage: python scripts/lock_gateway_requirements.py

Reads the exact pins in docker/gateway/requirements.in and downloads wheels only (no
source builds, so no package code runs) into a temporary directory for CPython 3.12 on
linux/amd64 and linux/arm64. It then writes every hash pip should accept. A lock
resolved on the host would carry the host's wheels (for example Windows builds of
pydantic-core), which is why this targets the image platforms explicitly.
"""

from __future__ import annotations

import hashlib
import re
import subprocess
import sys
import tempfile
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REQUIREMENTS_IN = ROOT / "docker" / "gateway" / "requirements.in"
REQUIREMENTS_TXT = ROOT / "docker" / "gateway" / "requirements.txt"
PLATFORMS = ("manylinux2014_x86_64", "manylinux2014_aarch64")
PYTHON = "3.12"


def main() -> int:
    hashes: dict[tuple[str, str], set[str]] = defaultdict(set)
    with tempfile.TemporaryDirectory(prefix="veritas-gateway-wheels-") as tmp:
        for platform in PLATFORMS:
            dest = Path(tmp) / platform
            subprocess.run(  # noqa: S603 - fixed argv built from constants
                [sys.executable, "-m", "pip", "download", "--quiet", "--disable-pip-version-check",
                 "--only-binary=:all:", "--platform", platform, "--python-version", PYTHON,
                 "--implementation", "cp", "--dest", str(dest), "-r", str(REQUIREMENTS_IN)],
                check=True,
            )  # fmt: skip
            for wheel in sorted(dest.glob("*.whl")):
                name, version = wheel.name.split("-")[:2]
                key = (re.sub(r"[-_.]+", "-", name).lower(), version)
                hashes[key].add(hashlib.sha256(wheel.read_bytes()).hexdigest())
    lines = [
        "# Generated by scripts/lock_gateway_requirements.py from requirements.in. Do not edit by hand.",
        f"# Targets: CPython {PYTHON} on {', '.join(PLATFORMS)}.",
    ]
    for (name, version), digests in sorted(hashes.items()):
        ordered = sorted(digests)
        lines.append(f"{name}=={version} \\")
        lines += [f"    --hash=sha256:{d} \\" for d in ordered[:-1]]
        lines.append(f"    --hash=sha256:{ordered[-1]}")
    REQUIREMENTS_TXT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {REQUIREMENTS_TXT.relative_to(ROOT)} ({len(hashes)} packages)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
